"""Сверка модулей управляемых форм обработки с их XML — то, чего не видит BSL Language Server.

    python3 scripts/form-check.py <каталог src обработки> [--names]

BSL LS анализирует модуль формы без метаданных формы: реквизиты для него — «неиспользуемые локальные переменные»,
обработчики из XML — «неиспользуемые методы». Опечатку в имени реквизита, элемента или обработчика он пропустит молча.
Скрипт проверяет по каждой форме:
  - каждый обработчик события и действие команды из Form.xml есть в модуле формы;
  - каждый элемент, на который модуль ссылается через Элементы./ЭлементыФормы., есть в Form.xml;
  - каждое Форма.<Имя> — реквизит формы, каждое Объект.<Имя> — реквизит обработки;
  - каждый реквизит формы где-то используется (в модуле или как DataPath элемента).
С --names печатает прочие идентификаторы модуля (не процедуры, не реквизиты, не элементы, не локальные) —
для просмотра глазами: там окажутся платформенные функции и модули БСП, а опечатка выделится.
Код возврата 1 — есть расхождения.
"""
import pathlib
import re
import sys

КЛЮЧЕВЫЕ = set("""Если Тогда Иначе ИначеЕсли КонецЕсли Для Каждого Из По Цикл КонецЦикла Пока Процедура КонецПроцедуры Функция
КонецФункции Возврат Экспорт Знач Истина Ложь Неопределено И Или Не Новый Попытка Исключение КонецПопытки Продолжить Прервать
Перем НаКлиенте НаСервере НаСервереБезКонтекста НаКлиентеНаСервереБезКонтекста Область КонецОбласти""".split())


def без_комментариев_и_строк(текст):
	текст = re.sub(r"//[^\n]*", "", текст)
	return re.sub(r'"[^"\n]*"', '""', текст)


def проверить_форму(каталог_формы, реквизиты_объекта, показать_имена):
	xml = (каталог_формы / "Ext" / "Form.xml").read_text(encoding="utf-8-sig")
	файл_модуля = каталог_формы / "Ext" / "Form" / "Module.bsl"
	модуль = файл_модуля.read_text(encoding="utf-8-sig") if файл_модуля.exists() else ""
	код = без_комментариев_и_строк(модуль)

	процедуры = set(re.findall(r"^(?:Процедура|Функция)\s+(\w+)", модуль, re.M))
	обработчики = set(re.findall(r'<Event name="\w+">(\w+)</Event>', xml)) | set(re.findall(r"<Action>(\w+)</Action>", xml))
	граница = xml.find("<Attributes>")
	элементы = set(re.findall(r'<\w+ name="(\w+)" id="-?\d+"', xml[:граница if граница >= 0 else len(xml)]))
	реквизиты = set(re.findall(r'<Attribute name="(\w+)"', xml))

	используемые_элементы = set(re.findall(r"(?:Элементы|ЭлементыФормы)\.(\w+)", код)) - {"Найти", "Добавить", "Удалить", "Переместить", "Вставить"}
	через_форму = set(re.findall(r"\bФорма\.(\w+)", код)) - {"Элементы", "Объект", "Команды", "Параметры", "УникальныйИдентификатор"}
	через_объект = set(re.findall(r"\bОбъект\.(\w+)", код))
	неиспользуемые = {р for р in реквизиты - {"Объект"} if not re.search(r"\b" + р + r"\b", код) and f"<DataPath>{р}" not in xml
		and f"<DataPath>{р}." not in xml}

	проблемы = []
	for заголовок, отсутствуют in (
			("обработчик или действие из XML не найдено в модуле", обработчики - процедуры),
			("элемента нет в XML", используемые_элементы - элементы),
			("Форма.<Имя> — нет такого реквизита формы", через_форму - реквизиты),
			("Объект.<Имя> — нет такого реквизита обработки", через_объект - реквизиты_объекта),
			("реквизит формы нигде не используется", неиспользуемые)):
		if отсутствуют: проблемы.append(f"  {заголовок}: {', '.join(sorted(отсутствуют))}")

	print(f"{каталог_формы.name}: {'ок' if not проблемы else 'РАСХОЖДЕНИЯ'}")
	for п in проблемы: print(п)

	if показать_имена:
		локальные = set()
		for параметры, тело in re.findall(r"^(?:Процедура|Функция)\s+\w+\(([^)]*)\)(.*?)^Конец(?:Процедуры|Функции)", код, re.M | re.S):
			локальные |= set(re.findall(r"(?:Знач\s+)?(\w+)\s*(?:=|,|$)", параметры))
			локальные |= set(re.findall(r"^\s*(\w+)\s*=", тело, re.M)) | set(re.findall(r"Для\s+(?:Каждого\s+)?(\w+)", тело))
		имена = set(re.findall(r"(?<![.\w&#])([А-Яа-яЁёA-Za-z_]\w*)", код))
		прочие = имена - КЛЮЧЕВЫЕ - процедуры - реквизиты - элементы - локальные - {"Форма"}
		print("  прочие имена:", ", ".join(sorted(прочие)))

	return not проблемы


def main():
	if len(sys.argv) < 2:
		print(__doc__); sys.exit(1)
	src = pathlib.Path(sys.argv[1])
	показать_имена = "--names" in sys.argv[2:]
	корни = [p for p in src.glob("*.xml")]
	if not корни: sys.exit(f"в {src} нет корневого XML обработки")
	корень = корни[0]
	реквизиты_объекта = set(re.findall(r"<Attribute uuid=\"[^\"]+\">\s*<Properties>\s*<Name>(\w+)</Name>", корень.read_text(encoding="utf-8-sig")))
	формы = sorted((src / корень.stem / "Forms").glob("*/")) if (src / корень.stem / "Forms").exists() else []
	все_ок = all([проверить_форму(ф, реквизиты_объекта, показать_имена) for ф in формы if (ф / "Ext" / "Form.xml").exists()])
	sys.exit(0 if все_ок else 1)


if __name__ == "__main__":
	main()
